-- ==========================================
-- 1. Lookup Tables (Roles, Statuses, Image Types)
-- ==========================================
CREATE TABLE CR_ROLES (
    ROLE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ROLE_CODE VARCHAR2(30) NOT NULL,
    ROLE_NAME VARCHAR2(100) NOT NULL,
    CONSTRAINT CR_ROLES_PK PRIMARY KEY (ROLE_ID),
    CONSTRAINT CR_ROLES_UKI UNIQUE (ROLE_CODE)
);

CREATE TABLE CR_REQUEST_STATUSES (
    STATUS_CODE VARCHAR2(30) NOT NULL,
    STATUS_NAME VARCHAR2(100) NOT NULL,
    DISPLAY_ORDER NUMBER NOT NULL,
    IS_FINAL CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT CR_REQUEST_STATUSES_PK PRIMARY KEY (STATUS_CODE),
    CONSTRAINT CR_REQUEST_STATUSES_UKI UNIQUE (STATUS_NAME),
    CONSTRAINT CR_REQUEST_STATUSES_CK1 CHECK (IS_FINAL IN ('Y','N'))
);

CREATE TABLE CR_IMAGE_TYPES (
    IMAGE_TYPE_CODE VARCHAR2(30) NOT NULL,
    IMAGE_TYPE_NAME VARCHAR2(100) NOT NULL,
    IS_REQUIRED CHAR(1) DEFAULT 'N' NOT NULL,
    SOURCE_RULE VARCHAR2(20) NOT NULL,
    CONSTRAINT CR_IMAGE_TYPES_PK PRIMARY KEY (IMAGE_TYPE_CODE),
    CONSTRAINT CR_IMAGE_TYPES_CK1 CHECK (IS_REQUIRED IN ('Y','N')),
    CONSTRAINT CR_IMAGE_TYPES_CK2 CHECK (SOURCE_RULE IN ('GALLERY','CAMERA'))
);

-- ==========================================
-- 2. Users & Security
-- ==========================================
CREATE TABLE CR_APP_USERS (
    USER_NAME VARCHAR2(255) NOT NULL,
    DISPLAY_NAME VARCHAR2(200) NOT NULL,
    IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT CR_APP_USERS_PK PRIMARY KEY (USER_NAME),
    CONSTRAINT CR_APP_USERS_CK1 CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE TABLE CR_USER_ROLES (
    USER_NAME VARCHAR2(255) NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    CONSTRAINT CR_USER_ROLES_PK PRIMARY KEY (USER_NAME, ROLE_ID),
    CONSTRAINT CR_USER_ROLES_FK1 FOREIGN KEY (USER_NAME) REFERENCES CR_APP_USERS(USER_NAME),
    CONSTRAINT CR_USER_ROLES_FK2 FOREIGN KEY (ROLE_ID) REFERENCES CR_ROLES(ROLE_ID)
);

-- ==========================================
-- 3. Main Request Table
-- ==========================================
CREATE TABLE CR_REQUEST (
    REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQUEST_NO VARCHAR2(30) NOT NULL,
    FULL_NAME VARCHAR2(200) NOT NULL,
    NATIONAL_ID VARCHAR2(30) NOT NULL,
    PHONE_NUMBER VARCHAR2(40) NOT NULL,
    EMAIL_ADDRESS VARCHAR2(320),
    VEHICLE_LICENSE_NO VARCHAR2(60) NOT NULL,
    MODEL_YEAR NUMBER(4) NOT NULL,
    MILEAGE_COUNTER NUMBER(12) NOT NULL,
    STATUS_CODE VARCHAR2(30) DEFAULT 'NEW' NOT NULL,
    ASSIGNED_TECHNICIAN VARCHAR2(255),
    LABOR_COST NUMBER(12,2),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(255),
    UPDATED_AT TIMESTAMP,
    CONSTRAINT CR_REQUEST_PK PRIMARY KEY (REQUEST_ID),
    CONSTRAINT CR_REQUEST_UKI UNIQUE (REQUEST_NO),
    CONSTRAINT CR_REQUEST_FK1 FOREIGN KEY (STATUS_CODE) REFERENCES CR_REQUEST_STATUSES(STATUS_CODE),
    CONSTRAINT CR_REQUEST_FK2 FOREIGN KEY (ASSIGNED_TECHNICIAN) REFERENCES CR_APP_USERS(USER_NAME),
    CONSTRAINT CR_REQUEST_CK1 CHECK (MODEL_YEAR BETWEEN 1950 AND 2100),
    CONSTRAINT CR_REQUEST_CK2 CHECK (MILEAGE_COUNTER >= 0),
    CONSTRAINT CR_REQUEST_CK3 CHECK (LABOR_COST IS NULL OR LABOR_COST >= 0)
);

-- ==========================================
-- 4. Images Table
-- ==========================================
CREATE TABLE CR_REQUEST_IMAGES (
    IMAGE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQUEST_ID NUMBER NOT NULL,
    IMAGE_TYPE_CODE VARCHAR2(30) NOT NULL,
    FILE_NAME VARCHAR2(255) NOT NULL,
    MIME_TYPE VARCHAR2(255) NOT NULL,
    FILE_SIZE NUMBER(12) NOT NULL,
    IMAGE_BLOB BLOB NOT NULL,
    UPLOADED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPLOADED_BY VARCHAR2(255),
    CONSTRAINT CR_REQUEST_IMAGES_PK PRIMARY KEY (IMAGE_ID),
    CONSTRAINT CR_REQUEST_IMAGES_FK1 FOREIGN KEY (REQUEST_ID) REFERENCES CR_REQUEST(REQUEST_ID) ON DELETE CASCADE,
    CONSTRAINT CR_REQUEST_IMAGES_FK2 FOREIGN KEY (IMAGE_TYPE_CODE) REFERENCES CR_IMAGE_TYPES(IMAGE_TYPE_CODE),
    CONSTRAINT CR_REQUEST_IMAGES_UKI UNIQUE (REQUEST_ID, IMAGE_TYPE_CODE),
    CONSTRAINT CR_REQUEST_IMAGES_CK1 CHECK (FILE_SIZE > 0)
);

-- ==========================================
-- 5. Parts Tables
-- ==========================================
CREATE TABLE CR_SPARE_PARTS (
    PART_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PART_CODE VARCHAR2(50) NOT NULL,
    PART_NAME VARCHAR2(200) NOT NULL,
    IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT CR_SPARE_PARTS_PK PRIMARY KEY (PART_ID),
    CONSTRAINT CR_SPARE_PARTS_UKI UNIQUE (PART_CODE),
    CONSTRAINT CR_SPARE_PARTS_CK1 CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE TABLE CR_REQUEST_PARTS (
    REQUEST_PART_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQUEST_ID NUMBER NOT NULL,
    PART_ID NUMBER,
    PART_DESCRIPTION VARCHAR2(200) NOT NULL,
    QUANTITY NUMBER(10,2) NOT NULL,
    UNIT_COST NUMBER(12,2) NOT NULL,
    CONSTRAINT CR_REQUEST_PARTS_PK PRIMARY KEY (REQUEST_PART_ID),
    CONSTRAINT CR_REQUEST_PARTS_FK1 FOREIGN KEY (REQUEST_ID) REFERENCES CR_REQUEST(REQUEST_ID) ON DELETE CASCADE,
    CONSTRAINT CR_REQUEST_PARTS_FK2 FOREIGN KEY (PART_ID) REFERENCES CR_SPARE_PARTS(PART_ID),
    CONSTRAINT CR_REQUEST_PARTS_CK1 CHECK (QUANTITY > 0),
    CONSTRAINT CR_REQUEST_PARTS_CK2 CHECK (UNIT_COST >= 0)
);

-- ==========================================
-- 6. History / Audit Table
-- ==========================================
CREATE TABLE CR_REQUEST_HISTORY (
    HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQUEST_ID NUMBER NOT NULL,
    FROM_STATUS VARCHAR2(30),
    TO_STATUS VARCHAR2(30) NOT NULL,
    ACTION_CODE VARCHAR2(40) NOT NULL,
    ACTOR_USER_NAME VARCHAR2(255) NOT NULL,
    NOTES VARCHAR2(2000),
    ACTION_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CR_REQUEST_HISTORY_PK PRIMARY KEY (HISTORY_ID),
    CONSTRAINT CR_REQUEST_HISTORY_FK1 FOREIGN KEY (REQUEST_ID) REFERENCES CR_REQUEST(REQUEST_ID) ON DELETE CASCADE,
    CONSTRAINT CR_REQUEST_HISTORY_FK2 FOREIGN KEY (FROM_STATUS) REFERENCES CR_REQUEST_STATUSES(STATUS_CODE),
    CONSTRAINT CR_REQUEST_HISTORY_FK3 FOREIGN KEY (TO_STATUS) REFERENCES CR_REQUEST_STATUSES(STATUS_CODE),
    CONSTRAINT CR_REQUEST_HISTORY_FK4 FOREIGN KEY (ACTOR_USER_NAME) REFERENCES CR_APP_USERS(USER_NAME)
);

-- ==========================================
-- 7. Performance Indexes
-- ==========================================
CREATE INDEX CR_Req_Status_IX ON CR_REQUEST (STATUS_CODE, CREATED_AT);
CREATE INDEX CR_Req_TECH_IX ON CR_REQUEST (ASSIGNED_TECHNICIAN, STATUS_CODE);
CREATE INDEX CR_IMG_Req_IX ON CR_REQUEST_IMAGES (REQUEST_ID);
CREATE INDEX CR_Part_Req_IX ON CR_REQUEST_PARTS (REQUEST_ID);
CREATE INDEX CR_Hist_Req_DATE_IX ON CR_REQUEST_HISTORY (REQUEST_ID, ACTION_AT);

-- ==========================================
-- 8. Generate Request Number Sequence (Optional helper)
-- ==========================================
CREATE SEQUENCE SEQ_CR_REQUEST_NO START WITH 1000 INCREMENT BY 1;